root <- normalizePath(Sys.getenv("SGCB_R2_ROOT"),winslash="/",mustWork=TRUE)
setwd(file.path(root,"release")); Sys.setenv(MAKEFLAGS="-j3")
r <- file.path(R.home("bin"),"R.exe")
pkg <- file.path(root,"software/SGCB"); lib <- if(identical(commandArgs(TRUE),"stage")) file.path(root,"tmp","staged_library") else file.path(root,"library")
dir.create(lib,showWarnings=FALSE)
stopifnot(as.character(read.dcf(file.path(pkg,"DESCRIPTION"),"Version"))=="0.6.0")
stopifnot(system2(r,c("CMD","build","--no-build-vignettes","--no-manual",shQuote(pkg)))==0)
tarball <- file.path(root,"release/SGCB_0.6.0.tar.gz")
stopifnot(system2(r,c("CMD","INSTALL","--no-multiarch","--preclean","-l",shQuote(lib),shQuote(tarball)))==0)
library(SGCB,lib.loc=lib)
stopifnot(as.character(packageVersion("SGCB",lib.loc=lib))=="0.6.0","endpoint"%in%names(formals(sgcbDE)))
cat("Installed",find.package("SGCB"),as.character(packageVersion("SGCB",lib.loc=lib)),"\n")