root <- normalizePath(Sys.getenv("SGCB_R2_ROOT"),mustWork=TRUE)
lib <- file.path(root,"library")
library(SGCB,lib.loc=lib)
stopifnot(as.character(packageVersion("SGCB",lib.loc=lib))=="0.6.0")
stopifnot(normalizePath(find.package("SGCB"),winslash="/")==normalizePath(file.path(lib,"SGCB"),winslash="/"))
reference <- new.env(parent=asNamespace("SGCB"))
sys.source(file.path(root,"software/SGCB/R/differential.R"),envir=reference)
stopifnot(identical(body(reference$sgcbDE),body(SGCB::sgcbDE)))
ledger <- data.table::fread(file.path(root,"results/analysis_versions.tsv"))
stopifnot(all(c("analysis","fitted_by","disposition","source")%in%names(ledger)))
cat("Reproduction loads SGCB 0.6.0 and its matching source. Saved author build identifiers describe record provenance only.\n")
